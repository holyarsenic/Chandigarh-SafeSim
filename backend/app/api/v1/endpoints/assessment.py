from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.ext.asyncio import AsyncSession
from app.core.database import get_db
from app.models.simulation import SimulationRecord
from app.schemas.assessment import AssessmentRequest, AssessmentResponse
from app.services.overpass import fetch_overpass_elements
from app.services.simulation_engine import simulate_disaster_impact
from app.services.gemini import generate_incident_brief

router = APIRouter()

@router.post("/simulate", response_model=AssessmentResponse)
async def run_assessment(payload: AssessmentRequest, db: AsyncSession = Depends(get_db)):
    if payload.radius not in [75, 150, 250]:
        raise HTTPException(status_code=400, detail="Radius must be 75, 150, or 250 meters.")

    raw_buildings, raw_roads = await fetch_overpass_elements(
        payload.latitude, payload.longitude, payload.radius
    )

    buildings, roads, hazard_index = simulate_disaster_impact(
        (payload.latitude, payload.longitude), payload.radius, raw_buildings, raw_roads
    )

    collapsed_bldgs = [b for b in buildings if b.properties["structural_damage_state"] == "COLLAPSED"]
    blocked_roads_names = [r.properties.get("name") or "Unnamed Road" for r in roads if r.properties["is_blocked"]]

    ai_brief = await generate_incident_brief(
        payload.latitude, payload.longitude, payload.radius,
        hazard_index, len(collapsed_bldgs), blocked_roads_names
    )

    data_payload = {
        "location": {"latitude": payload.latitude, "longitude": payload.longitude},
        "radiusMeters": payload.radius,
        "buildings": {
            "count": len(buildings),
            "type": "FeatureCollection",
            "features": [b.model_dump() for b in buildings]
        },
        "roads": {
            "count": len(roads),
            "type": "FeatureCollection",
            "features": [r.model_dump() for r in roads]
        },
        "disclaimer": "Disaster physics & collapse risk assessment generated by Chandigarh-SafeSim engine."
    }

    record = SimulationRecord(
        latitude=payload.latitude,
        longitude=payload.longitude,
        radius=payload.radius,
        hazard_index=hazard_index,
        total_buildings=len(buildings),
        collapsed_buildings_count=len(collapsed_bldgs),
        blocked_roads_count=len(blocked_roads_names),
        geojson_payload=data_payload,
        ai_incident_brief=ai_brief.model_dump() if ai_brief else None
    )
    db.add(record)
    await db.commit()
    await db.refresh(record)

    return AssessmentResponse(
        success=True,
        data=data_payload,
        simulation_id=record.id,
        overall_hazard_index=hazard_index,
        ai_brief=ai_brief
    )